def current_language_code() -> str:
    lang = (get_language() or "ru").lower()
    return "en" if lang.startswith("en") else "ru"


def translate(message: str) -> str:
    if not message:
        return message
    if current_language_code() != "en":
        return message
    return EN.get(message, message)
